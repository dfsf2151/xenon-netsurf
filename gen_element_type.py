#!/usr/bin/env python3
"""Generate libhubbub's element-type table without gperf.

The upstream Makefile runs `gperf` to turn element-type.gperf into
autogenerated-element-type.c with a perfect hash. A linear scan over 107
entries is just as good for our purposes and removes the build-time tool.
"""
import pathlib
import sys

root = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(".")
gperf = root / "src/treebuilder/element-type.gperf"
out = root / "src/treebuilder/autogenerated-element-type.c"

body = gperf.read_text().split("%%", 1)[1]
entries = []
for line in body.splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    name, typ = (part.strip() for part in line.split(",", 1))
    entries.append((name, typ))

lines = [
    "/* Generated from element-type.gperf without gperf (linear lookup). */",
    "#include <stddef.h>",
    "#include <string.h>",
    "#include <strings.h>",
    '#include "treebuilder/element-type.h"',
    "",
    "static const struct element_type_map wordlist[] = {",
]
for name, typ in entries:
    lines.append('    { "%s", %s },' % (name, typ))
lines += [
    "};",
    "",
    "static const struct element_type_map *",
    "hubbub_element_type_generated_lookup(const char *str, size_t len)",
    "{",
    "\tsize_t i;",
    "",
    "\tfor (i = 0; i < sizeof(wordlist) / sizeof(wordlist[0]); i++) {",
    "\t\tif (strlen(wordlist[i].name) == len &&",
    "\t\t    strncasecmp(str, wordlist[i].name, len) == 0)",
    "\t\t\treturn &wordlist[i];",
    "\t}",
    "",
    "\treturn NULL;",
    "}",
    "",
]
out.write_text("\n".join(lines))
print(f"wrote {out} ({len(entries)} entries)")
